import { chmodSync, existsSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { sq } from "../spawn/launcher.ts";

/** Marks a plugin file written by `sentinel swiftbar install`, so reinstalling may overwrite it. */
export const PLUGIN_MARKER = "Generated by `sentinel swiftbar install`";
/** File name used when the install path is a directory: refreshed by SwiftBar every 30s. */
export const DEFAULT_PLUGIN_NAME = "sentinel.30s.sh";

export interface PluginOptions {
  /** argv prefix that runs Sentinel. */
  self: string[];
  /** SwiftBar runs plugins with a minimal PATH; the installing shell's PATH lets the daemon find gh, rex and the agents. */
  path?: string;
  /** Kept only when set, so the plugin talks to the same daemon as the installing shell. */
  sentinelHome?: string;
}

/**
 * The plugin is a thin wrapper: with no arguments it prints the menu, and menu actions run it again
 * with the action as arguments (`go <session>`, `refresh`, ...), both handled by `sentinel swiftbar`.
 */
export function pluginScript(o: PluginOptions): string {
  const env = [
    ...(o.path ? [`export PATH=${sq(o.path)}`] : []),
    ...(o.sentinelHome ? [`export SENTINEL_HOME=${sq(o.sentinelHome)}`] : []),
  ];
  return `#!/bin/bash
# Agent Sentinel for SwiftBar: agent sessions with their PRs and Jira tickets.
# ${PLUGIN_MARKER}; run it again to update this file.
#
# <xbar.title>Agent Sentinel</xbar.title>
# <xbar.desc>Agent sessions watched by Sentinel, with their PRs and Jira tickets</xbar.desc>
# <swiftbar.hideAbout>true</swiftbar.hideAbout>
# <swiftbar.hideRunInTerminal>true</swiftbar.hideRunInTerminal>
# <swiftbar.hideDisablePlugin>false</swiftbar.hideDisablePlugin>

${env.join("\n")}
SENTINEL=(${o.self.map(sq).join(" ")})

if [ $# -gt 0 ]; then
  exec "\${SENTINEL[@]}" swiftbar "$@"
fi
exec "\${SENTINEL[@]}" swiftbar menu --plugin "$0"
`;
}

/** Where to write the plugin: `dir/sentinel.30s.sh` for an existing directory, else the given `.sh` file. */
export function resolvePluginPath(input: string, cwd = process.cwd()): string {
  const expanded = input === "~" ? homedir() : input.startsWith("~/") ? join(homedir(), input.slice(2)) : input;
  const abs = resolve(cwd, expanded);
  if (existsSync(abs) && statSync(abs).isDirectory()) return join(abs, DEFAULT_PLUGIN_NAME);
  if (!abs.endsWith(".sh")) throw new Error(`${abs} is not a directory or a .sh file`);
  if (!existsSync(dirname(abs))) throw new Error(`directory ${dirname(abs)} does not exist`);
  return abs;
}

/**
 * Writes the plugin and makes it executable. Refuses to replace a file it didn't write unless `force`.
 * SwiftBar can't pass a `"` in a menu action's path, so such paths are refused.
 */
export function installPlugin(file: string, o: PluginOptions & { force?: boolean }): "installed" | "updated" {
  if (file.includes('"')) throw new Error(`the plugin path can't contain a double quote: ${file}`);
  const existed = existsSync(file);
  if (existed && !o.force && !readFileSync(file, "utf8").includes(PLUGIN_MARKER)) {
    throw new Error(`${file} exists and wasn't written by Sentinel; pass --force to replace it`);
  }
  writeFileSync(file, pluginScript(o));
  chmodSync(file, 0o755);
  return existed ? "updated" : "installed";
}
